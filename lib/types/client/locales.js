export function t(locale, key, params) {
    const dict = locale?.zh ?? zh;
    let template = dict[key];
    if (params !== undefined) {
        for (const [name, value] of Object.entries(params)) {
            template = template.replace(`{${name}}`, String(value));
        }
    }
    return template;
}
